"""Keep the MTL Retail IQ Fabric App database and the Gold lakehouse in sync.

Read path:  MTL_Gold (SQL analytics endpoint) -> app SQL database snapshot tables (replaced in one transaction).
Write path: app ReorderRequests -> (Fabric SQL database OneLake replica) -> Bronze shortcut -> 06_Gold_Reorder_Requests
            -> gold reorder_requests -> ReorderReviews written back to the app for each requester.

Usage: python app_sync.py [config|discover|publish|land|reviews|sync|status]
"""
from datetime import datetime, timezone
import json
import sys
import time

import fabric as f
import medallion
from model import gold_connection, refresh_sql_endpoint

APP_DIR = f.ROOT / "app"


def now():
    return datetime.now(timezone.utc).replace(microsecond=0)


def config():
    """Generate the function constants from the deployed agent and ontology (no hand-edited IDs)."""
    tools = f.load("agent-mcp-tools.json")["tools"]
    names = [t["name"] for t in tools if "userQuestion" in t.get("inputSchema", {}).get("properties", {})]
    if len(names) != 1:
        raise RuntimeError("Expected one Data Agent MCP tool")
    content = ("// Generated by app_sync.py config from ../../../../artifacts. Do not edit by hand.\n"
               f"export const WORKSPACE_ID = '{f.ws()}';\n"
               f"export const AGENT_ID = '{f.load('agent.json')['id']}';\n"
               f"export const ONTOLOGY_ID = '{f.load('ontology.json')['id']}';\n"
               "export const AGENT_NAME = 'MTL Retail IQ Advisor';\n"
               f"export const AGENT_TOOL_NAME = '{names[0]}';\n"
               "export const ONTOLOGY_NAME = 'MtlRetailOntology';\n")
    (APP_DIR / "rayfin" / "functions" / "src" / "fabric_config.ts").write_text(content, encoding="utf-8")
    return {"toolName": names[0]}


def discover():
    deployments = json.loads((APP_DIR / "rayfin" / ".deployments.json").read_text(encoding="utf-8"))
    active = deployments["deployments"][deployments["active"]]
    if active["fabricWorkspaceId"] != f.ws():
        raise RuntimeError("App is deployed to a different workspace")
    item = active["fabricItemId"]
    databases = [d for d in f.listing(f.path() + "/sqlDatabases") if d["displayName"].startswith(active["itemName"])]
    if len(databases) != 1:
        raise RuntimeError("Could not identify the app SQL database: " + json.dumps([d["displayName"] for d in databases]))
    db = f.api(f.path() + "/sqlDatabases/" + databases[0]["id"])
    app = {"appBackendId": item, "name": active["itemName"], "url": active["hostingUrl"],
           "portal": active["fabricDeepLink"], "sqlDatabaseId": db["id"], "server": db["properties"]["serverFqdn"].split(",")[0],
           "database": db["properties"]["databaseName"], "workspaceId": f.ws(), "deployedAt": active["deployedAt"]}
    f.save("app.json", app)
    return app


def app_conn():
    app = f.load("app.json")
    return f.sql_connect(app["server"], app["database"], app="MtlRetailIQSync")


def tables(conn):
    names = [r[0] for r in conn.execute("SELECT name FROM sys.tables WHERE schema_id = SCHEMA_ID('dbo')").fetchall()]

    def find(entity):
        match = [n for n in names if n.lower() in (entity.lower(), entity.lower() + "s")]
        if len(match) != 1:
            raise RuntimeError(f"App table for {entity} not found in {names}")
        return "dbo.[" + match[0] + "]"
    return find


def fetch(conn, sql):
    cursor = conn.execute(sql)
    names = [c[0] for c in cursor.description]
    return [dict(zip(names, row)) for row in cursor.fetchall()]


def gold_snapshot():
    refresh_sql_endpoint()
    with gold_connection() as g:
        chain = fetch(g, "SELECT * FROM kpi_chain_summary")[0]
        risk = fetch(g, "SELECT SUM(CASE WHEN RiskLevel = 'Critical' THEN 1 ELSE 0 END) AS critical, "
                        "SUM(CASE WHEN RiskLevel = 'High' THEN 1 ELSE 0 END) AS high, "
                        "SUM(CASE WHEN RiskLevel IN ('Critical', 'High') THEN RecommendedReorderQty ELSE 0 END) AS rec, "
                        "MAX(ModelName + ' v' + ModelVersion) AS model FROM ml_stock_risk")[0]
        forecast = fetch(g, "SELECT SUM(ForecastUnits) AS units, SUM(ForecastNetSales) AS sales, "
                            "MAX(ModelName + ' v' + ModelVersion) AS model FROM ml_sales_forecast_daily")[0]
        wape = fetch(g, "SELECT Value, BaselineValue FROM ml_model_metrics WHERE Metric = 'WAPE' AND Segment = 'Holdout (department-day)'")[0]
        data = {
            "KpiSnapshot": [{
                "snapshotDate": str(chain["SnapshotDate"])[:10], "publishedAt": now().isoformat().replace("+00:00", "Z"),
                "netSalesLast28": chain["NetSalesLast28"], "netSalesLast28LY": chain["NetSalesLast28LY"],
                "last28GrowthPct": chain["Last28GrowthPct"], "unitsLast28": int(chain["UnitsLast28"]),
                "grossMarginPctLast28": chain["GrossMarginPctLast28"], "netSalesYTD": chain["NetSalesYTD"],
                "ytdGrowthPct": chain["YTDGrowthPct"], "storeOnHandUnits": int(chain["StoreOnHandUnits"]),
                "storeOnOrderUnits": int(chain["StoreOnOrderUnits"]), "dcOnHandUnits": int(chain["DcOnHandUnits"]),
                "inventoryCost": chain["InventoryCost"], "positions": int(chain["Positions"]),
                "outOfStockPositions": int(chain["OutOfStockPositions"]),
                "belowReorderPointPositions": int(chain["BelowReorderPointPositions"]), "criticalPositions": int(risk["critical"]),
                "highRiskPositions": int(risk["high"]), "recommendedUnitsHighRisk": int(risk["rec"]),
                "forecastUnits28": int(round(forecast["units"])), "forecastNetSales28": round(forecast["sales"], 2),
                "forecastWapePct": round(wape["Value"], 2), "baselineWapePct": round(wape["BaselineValue"], 2),
                "forecastModel": forecast["model"], "stockModel": risk["model"], "generatedAt": now().replace(tzinfo=None)}],
            "StoreKpi": fetch(g, """
                SELECT k.StoreCode AS storeCode, k.StoreName AS storeName, k.City AS city, k.Region AS region,
                       k.NetSalesLast28 AS netSalesLast28, k.NetSalesLast28LY AS netSalesLast28LY, k.Last28GrowthPct AS last28GrowthPct,
                       CAST(k.UnitsLast28 AS int) AS unitsLast28, k.GrossMarginPctLast28 AS grossMarginPctLast28,
                       k.NetSalesYTD AS netSalesYTD, k.YTDGrowthPct AS ytdGrowthPct, CAST(k.OnHandUnits AS int) AS onHandUnits,
                       CAST(k.OutOfStockPositions AS int) AS outOfStockPositions,
                       CAST(k.BelowReorderPointPositions AS int) AS belowReorderPointPositions,
                       CAST(r.high AS int) AS highRiskPositions, CAST(ROUND(fc.units, 0) AS int) AS forecastUnits28
                FROM kpi_store_summary k
                JOIN (SELECT StoreCode, SUM(CASE WHEN RiskLevel IN ('Critical', 'High') THEN 1 ELSE 0 END) AS high
                      FROM ml_stock_risk GROUP BY StoreCode) r ON r.StoreCode = k.StoreCode
                JOIN (SELECT StoreCode, SUM(Forecast28Units) AS units FROM ml_forecast_summary GROUP BY StoreCode) fc
                  ON fc.StoreCode = k.StoreCode"""),
            "CategoryKpi": fetch(g, """
                SELECT CategoryPerformanceId AS categoryId, Department AS department, Category AS category,
                       COALESCE(NetSalesLast28, 0) AS netSalesLast28, Last28GrowthPct AS last28GrowthPct,
                       CAST(COALESCE(UnitsLast28, 0) AS int) AS unitsLast28, GrossMarginPctLast28 AS grossMarginPctLast28,
                       CAST(OnHandUnits AS int) AS onHandUnits, SellThroughPctLast28 AS sellThroughPct, WeeksOfSupply AS weeksOfSupply,
                       CAST(OutOfStockPositions AS int) AS outOfStockPositions FROM kpi_category_summary"""),
            "ProductKpi": fetch(g, """
                SELECT p.SKU AS sku, p.ProductName AS productName, p.Department AS department, p.Category AS category,
                       p.Brand AS brand, p.SupplierCode AS supplierCode, p.UnitPrice AS unitPrice, p.CasePack AS casePack,
                       COALESCE(s.net28, 0) AS netSalesLast28, CAST(COALESCE(s.units28, 0) AS int) AS unitsLast28,
                       CASE WHEN s.netLy > 0 THEN ROUND((s.net28 / s.netLy - 1) * 100, 2) END AS last28GrowthPct,
                       CAST(i.onHand AS int) AS onHandUnits, CAST(i.dc AS int) AS dcOnHandUnits, CAST(i.oos AS int) AS outOfStockStores,
                       CAST(i.below AS int) AS belowReorderPointStores, CAST(ROUND(fc.units, 0) AS int) AS forecastUnits28
                FROM dim_product p
                LEFT JOIN (SELECT f.SKU, SUM(CASE WHEN d.IsLast28Days = 1 THEN f.NetSales END) AS net28,
                                  SUM(CASE WHEN d.IsLast28Days = 1 THEN f.UnitsSold END) AS units28,
                                  SUM(CASE WHEN d.IsLast28DaysLY = 1 THEN f.NetSales END) AS netLy
                           FROM fact_sales f JOIN dim_date d ON d.DateKey = f.DateKey
                           WHERE d.IsLast28Days = 1 OR d.IsLast28DaysLY = 1 GROUP BY f.SKU) s ON s.SKU = p.SKU
                JOIN (SELECT SKU, SUM(OnHandUnits) AS onHand, MAX(DcOnHandUnits) AS dc,
                             SUM(CASE WHEN IsOutOfStock = 1 THEN 1 ELSE 0 END) AS oos,
                             SUM(CASE WHEN IsBelowReorderPoint = 1 THEN 1 ELSE 0 END) AS below
                      FROM inventory_current GROUP BY SKU) i ON i.SKU = p.SKU
                JOIN (SELECT SKU, SUM(Forecast28Units) AS units FROM ml_forecast_summary GROUP BY SKU) fc ON fc.SKU = p.SKU"""),
            "MonthlyTrend": fetch(g, """
                SELECT FORMAT(c.MonthStart, 'yyyy-MM') AS month, c.Department AS department, c.net AS netSales, l.net AS netSalesLY,
                       CAST(c.units AS int) AS units
                FROM (SELECT MonthStart, Department, SUM(NetSales) AS net, SUM(UnitsSold) AS units
                      FROM sales_month_store_category GROUP BY MonthStart, Department) c
                LEFT JOIN (SELECT MonthStart, Department, SUM(NetSales) AS net
                           FROM sales_month_store_category GROUP BY MonthStart, Department) l
                  ON l.Department = c.Department AND l.MonthStart = DATEADD(month, -12, c.MonthStart)
                WHERE c.MonthStart >= '2025-01-01'"""),
            "DemandPoint": fetch(g, """
                SELECT CONVERT(varchar(10), Date, 23) AS day, Department AS department, Kind AS kind, ROUND(Units, 2) AS units,
                       ROUND(UnitsLow, 2) AS unitsLow, ROUND(UnitsHigh, 2) AS unitsHigh FROM ml_forecast_chart"""),
            "StockRisk": fetch(g, """
                SELECT PositionId AS positionId, StoreCode AS storeCode, StoreName AS storeName, SKU AS sku, ProductName AS productName,
                       Department AS department, Category AS category, OnHandUnits AS onHandUnits, OnOrderUnits AS onOrderUnits,
                       ReorderPointUnits AS reorderPointUnits, DaysOfSupply AS daysOfSupply, StockStatus AS stockStatus,
                       ROUND(Forecast28Units, 2) AS forecast28Units, CONVERT(varchar(10), PredictedLowStockDate, 23) AS predictedLowStockDate,
                       CAST(PredictedDaysToLow AS int) AS predictedDaysToLow, RiskLevel AS riskLevel, RiskRank AS riskRank,
                       RecommendedReorderQty AS recommendedReorderQty, RecommendedAction AS recommendedAction,
                       DcOnHandUnits AS dcOnHandUnits FROM ml_stock_risk"""),
        }
    expected = f.load("expected.json")
    k = data["KpiSnapshot"][0]
    if k["outOfStockPositions"] != expected["outOfStockPositions"] or abs(k["netSalesLast28"] - expected["netSalesLast28"]) > 0.05:
        raise RuntimeError("Gold snapshot does not match governed controls")
    return data


def publish():
    data = gold_snapshot()
    conn = app_conn()
    find = tables(conn)
    conn.autocommit = False
    counts = {}
    try:
        cursor = conn.cursor()
        cursor.fast_executemany = True
        for entity, rows in data.items():
            table = find(entity)
            columns = list(rows[0])
            cursor.execute(f"DELETE FROM {table}")
            cursor.executemany(f"INSERT INTO {table} (id, {', '.join(columns)}) VALUES (NEWID(), {', '.join('?' * len(columns))})",
                               [[r[c] for c in columns] for r in rows])
            counts[entity] = conn.execute(f"SELECT COUNT(*) FROM {table}").fetchval()
            if counts[entity] != len(rows):
                raise RuntimeError(f"{entity}: wrote {counts[entity]} rows, expected {len(rows)}")
        stored = conn.execute(f"SELECT netSalesLast28, outOfStockPositions FROM {find('KpiSnapshot')}").fetchone()
        if abs(float(stored[0]) - data["KpiSnapshot"][0]["netSalesLast28"]) > 0.01 or stored[1] != data["KpiSnapshot"][0]["outOfStockPositions"]:
            raise RuntimeError("Published snapshot read-back mismatch")
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.autocommit = True
    evidence = {"publishedAt": data["KpiSnapshot"][0]["publishedAt"], "rows": counts,
                "snapshot": {k: v for k, v in data["KpiSnapshot"][0].items() if k != "generatedAt"}}
    f.save("app-sync-publish.json", evidence)
    return evidence


def land():
    return medallion.app_shortcut()


def requests():
    conn = app_conn()
    return fetch(conn, f"SELECT id, storeCode, sku, quantity, urgency, user_id, submittedAt FROM {tables(conn)('ReorderRequest')}")


def reviews(wait=600):
    """Run the reorder conformance notebook once the app rows have replicated, then write reviews back to the app."""
    pending = {str(r["id"]).lower(): r for r in requests()}
    if not pending:
        return {"requests": 0}
    land()
    deadline = time.time() + wait
    while True:
        medallion.run("nb_reorders", True)
        refresh_sql_endpoint()
        with gold_connection() as g:
            gold = {r["RequestId"]: r for r in fetch(g, "SELECT RequestId, WorkflowStatus, ValidationMessage, RiskLevel, "
                                                        "RecommendedReorderQty FROM reorder_requests")}
        missing = sorted(set(pending) - set(gold))
        if not missing or time.time() > deadline:
            break
        print(f"{len(missing)} requests not yet replicated to OneLake; retrying", flush=True)
        time.sleep(60)
    conn = app_conn()
    table = tables(conn)("ReorderReview")
    reviewed_at = now().isoformat().replace("+00:00", "Z")
    rows = [[rid, pending[rid]["user_id"], g["WorkflowStatus"], (g["ValidationMessage"] or "")[:300], g["RiskLevel"],
             None if g["RecommendedReorderQty"] is None else int(g["RecommendedReorderQty"]), reviewed_at]
            for rid, g in gold.items() if rid in pending]
    conn.autocommit = False
    try:
        cursor = conn.cursor()
        for row in rows:
            cursor.execute(f"DELETE FROM {table} WHERE requestId = ?", row[0])
        if rows:
            cursor.executemany(f"INSERT INTO {table} (id, requestId, user_id, status, message, riskLevel, recommendedQty, reviewedAt) "
                               "VALUES (NEWID(), ?, ?, ?, ?, ?, ?, ?)", rows)
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.autocommit = True
    evidence = {"appRequests": len(pending), "conformedInGold": len(gold), "reviewsWritten": len(rows),
                "notYetReplicated": missing, "statuses": sorted({r[2] for r in rows}), "reviewedAt": reviewed_at}
    f.save("app-sync-reviews.json", evidence)
    return evidence


def status():
    conn = app_conn()
    find = tables(conn)
    return {entity: conn.execute(f"SELECT COUNT(*) FROM {find(entity)}").fetchval()
            for entity in ["KpiSnapshot", "StoreKpi", "CategoryKpi", "ProductKpi", "MonthlyTrend", "DemandPoint", "StockRisk",
                           "ReorderRequest", "ReorderReview"]}


def main(argv):
    steps = argv or ["status"]
    for step in steps:
        print("==", step, flush=True)
        if step == "sync":
            result = {"reviews": reviews(), "publish": publish()}
        else:
            result = {"config": config, "discover": discover, "publish": publish, "land": land, "reviews": reviews,
                      "status": status}[step]()
        print(json.dumps(result, indent=2, default=str), flush=True)


if __name__ == "__main__":
    main(sys.argv[1:])
